#!/usr/bin/env node
'use strict';

/*
 * Zero-dependency static generator for the board game catalog.
 *
 *   node scripts/build.js            # rewrite list page + every detail page
 *   node scripts/build.js --check    # validate and compare, write nothing
 *   node scripts/build.js --out DIR  # write to another visible directory
 *
 * The list page keeps its hand-written shell (header, hero, CSS, filter JS)
 * in index.html. Build replaces only the marked blocks:
 *   CHIPS, CARDS, STATS, JSONLD
 *
 * Detail pages are generated whole at <slug>/index.html and carry a marker
 * comment so stale pages can be removed safely. Output is deterministic:
 * running build twice produces byte-identical files.
 */

var fs = require('fs');
var path = require('path');
var data = require('./lib/data.js');

var ROOT = data.ROOT;
var BASE = '/games/boardgames/';
var CANONICAL = 'https://hhfa008.github.io/games/boardgames/';
var GENERATED_MARK = '<!-- generated by boardgames/scripts/build.js -->';
var DETAIL_SKIP_DIRS = ['data', 'scripts', 'schema', 'fixtures', 'tests', 'test-output', 'node_modules'];

function parseArgs(argv) {
  var opts = { check: false, out: ROOT, quiet: false };
  for (var i = 0; i < argv.length; i++) {
    var arg = argv[i];
    if (arg === '--check') opts.check = true;
    else if (arg === '--quiet') opts.quiet = true;
    else if (arg === '--out') opts.out = path.resolve(argv[++i]);
    else if (arg.indexOf('--out=') === 0) opts.out = path.resolve(arg.slice(6));
    else if (arg === '--help' || arg === '-h') {
      console.log('usage: node scripts/build.js [--check] [--out DIR] [--quiet]');
      process.exit(0);
    } else {
      console.error('unknown argument: ' + arg);
      process.exit(1);
    }
  }
  return opts;
}

function h(value) {
  return data.escapeHtml(value);
}

function replaceBlock(html, name, body) {
  var start = '<!-- BOARDGAMES:' + name + ':START -->';
  var end = '<!-- BOARDGAMES:' + name + ':END -->';
  var a = html.indexOf(start);
  var b = html.indexOf(end, a + start.length);
  if (a < 0 || b < 0) {
    throw new Error('index.html is missing marker block ' + name + ' (' + start + ' / ' + end + ')');
  }
  return html.slice(0, a + start.length) + '\n' + body + '\n' + html.slice(b);
}

function renderChips(categories, games) {
  var counts = data.countByCategory(games);
  var out = ['<button type="button" class="chip is-on" data-cat="all" aria-pressed="true">全部 <span class="chip-count">' + games.length + '</span></button>'];
  categories.slice().sort(function (a, b) { return a.order - b.order; }).forEach(function (cat) {
    out.push('<button type="button" class="chip" data-cat="' + h(cat.id) + '" aria-pressed="false">' +
      h(cat.zh) + ' <span class="chip-count">' + (counts[cat.id] || 0) + '</span></button>');
  });
  return out.join('\n');
}

function renderStats(games, categories) {
  return '<p class="catalog-meta" id="catalog-meta">共 <span id="catalog-total">' + games.length +
    '</span> 款游戏 · <span id="catalog-shown">' + games.length + '</span> 款显示中 · ' +
    categories.length + ' 个品类 · 评分与重度为约值</p>';
}

function renderCard(game, catMap) {
  var searchParts = [
    game.slug,
    game.name,
    game.nameOriginal,
    game.description || '',
    game.categories.map(function (id) { return catMap[id] ? catMap[id].zh + ' ' + catMap[id].en : id; }).join(' '),
    (game.designers || []).join(' '),
    (game.publishers || []).join(' '),
    game.year == null ? '' : String(game.year)
  ];
  return '<article class="game-card" data-slug="' + h(game.slug) + '"' +
    ' data-categories="' + h(game.categories.join(' ')) + '"' +
    ' data-players-min="' + game.playersMin + '" data-players-max="' + game.playersMax + '"' +
    ' data-time-min="' + game.playTimeMin + '" data-time-max="' + game.playTimeMax + '"' +
    ' data-name="' + h(game.name) + '" data-name-original="' + h(game.nameOriginal) + '"' +
    ' data-designers="' + h((game.designers || []).join('|')) + '"' +
    ' data-publishers="' + h((game.publishers || []).join('|')) + '"' +
    ' data-year="' + (game.year == null ? '' : game.year) + '"' +
    ' data-search="' + h(searchParts.join(' ').toLowerCase()) + '">\n' +
    '  <a href="' + BASE + game.slug + '/">\n' +
    '    <div class="cover" style="background:' + h(game.cover.gradient) + '" aria-hidden="true"><span>' + h(game.cover.label) + '</span></div>\n' +
    '    <div class="card-body">\n' +
    '      <div class="card-head"><h3>' + h(game.name) + '</h3><span class="latin">' + h(game.nameOriginal) + '</span></div>\n' +
    '      <p class="desc">' + h(game.description || '暂无简介。') + '</p>\n' +
    '      <p class="tags"><span class="people">' + h(data.formatPlayers(game)) + '</span>' +
    '<span>' + h(data.formatTime(game)) + '</span>' +
    '<span>重度 ' + h(data.formatWeight(game)) + '</span>' +
    '<span>评分 ' + h(data.formatRating(game)) + '</span></p>\n' +
    '    </div>\n' +
    '  </a>\n' +
    '</article>';
}

function listJsonLd(games) {
  return JSON.stringify({
    '@context': 'https://schema.org',
    '@type': 'CollectionPage',
    name: '桌游资料库',
    url: CANONICAL,
    inLanguage: 'zh-CN',
    description: '收录 ' + games.length + ' 款桌游的名称、人数、时长、重度、评分与出版信息，可按品类、人数、时长筛选。',
    isPartOf: { '@type': 'WebSite', name: 'Devin', url: 'https://hhfa008.github.io/' },
    mainEntity: {
      '@type': 'ItemList',
      numberOfItems: games.length,
      itemListElement: games.map(function (game, i) {
        return {
          '@type': 'ListItem',
          position: i + 1,
          name: game.name,
          alternateName: game.nameOriginal,
          url: CANONICAL + game.slug + '/'
        };
      })
    }
  }, null, 2);
}

function renderList(template, categories, games) {
  var catMap = data.categoryMap(categories);
  var html = replaceBlock(template, 'CHIPS', renderChips(categories, games));
  html = replaceBlock(html, 'STATS', renderStats(games, categories));
  html = replaceBlock(html, 'CARDS', games.map(function (game) { return renderCard(game, catMap); }).join('\n\n'));
  html = replaceBlock(html, 'JSONLD', '<script type="application/ld+json">\n' + listJsonLd(games) + '\n</script>');
  return html;
}

function detailJsonLd(game, catMap) {
  var json = {
    '@context': 'https://schema.org',
    '@type': 'BoardGame',
    name: game.name,
    alternateName: game.nameOriginal,
    url: CANONICAL + game.slug + '/',
    inLanguage: 'zh-CN',
    description: game.description || '',
    genre: game.categories.map(function (id) { return catMap[id] ? catMap[id].zh : id; }),
    numberOfPlayers: {
      '@type': 'QuantitativeValue',
      minValue: game.playersMin,
      maxValue: game.playersMax
    }
  };
  if (game.year != null) json.datePublished = String(game.year);
  if (typeof game.rating === 'number') {
    json.aggregateRating = {
      '@type': 'AggregateRating',
      ratingValue: game.rating,
      bestRating: 10,
      worstRating: 0
    };
  }
  if (game.designers.length) {
    json.author = game.designers.map(function (name) { return { '@type': 'Person', name: name }; });
  }
  if (game.publishers.length) {
    json.publisher = game.publishers.map(function (name) { return { '@type': 'Organization', name: name }; });
  }
  return json;
}

function detailSourceLabel(source) {
  var labels = { fixture: '离线 fixture', bgg: 'BGG 公开资料', gstone: 'GStone 公开页面', manual: '人工整理' };
  return (labels[source.type] || source.type) + ' · ' + source.fetchedAt;
}

