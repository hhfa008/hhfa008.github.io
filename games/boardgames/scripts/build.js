function writeIfChanged(file, content) {
  if (fs.existsSync(file)) {
    var old = fs.readFileSync(file, 'utf8');
    if (old === content) return false;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  var tmp = file + '.tmp-' + process.pid;
  fs.writeFileSync(tmp, content);
  fs.renameSync(tmp, file);
  return true;
}

function staleGeneratedDirs(out, slugs) {
  var result = [];
  if (!fs.existsSync(out)) return result;
  fs.readdirSync(out, { withFileTypes: true }).forEach(function (ent) {
    if (!ent.isDirectory()) return;
    if (ent.name.charAt(0) === '.') return;
    if (DETAIL_SKIP_DIRS.indexOf(ent.name) !== -1) return;
    if (slugs.indexOf(ent.name) !== -1) return;
    var index = path.join(out, ent.name, 'index.html');
    if (!fs.existsSync(index)) return;
    if (fs.readFileSync(index, 'utf8').indexOf(GENERATED_MARK) !== -1) result.push(ent.name);
  });
  return result;
}

function main() {
  var opts = parseArgs(process.argv.slice(2));
  var categories;
  var games;
  var schema;
  try {
    categories = data.loadCategories();
    games = data.loadGames();
    schema = data.loadSchema();
  } catch (err) {
    console.error('[build] cannot load catalog: ' + err.message);
    process.exitCode = 1;
    return;
  }

  var errors = data.validateCatalog(categories, games, schema);
  if (errors.length) {
    console.error('[build] catalog validation failed:');
    errors.slice(0, 40).forEach(function (err) {
      console.error('  ' + err.path + ': ' + err.message);
    });
    process.exitCode = 1;
    return;
  }

  var templatePath = path.join(ROOT, 'index.html');
  if (!fs.existsSync(templatePath)) {
    console.error('[build] missing list page template: ' + templatePath);
    process.exitCode = 1;
    return;
  }
  var template = fs.readFileSync(templatePath, 'utf8');
  var listHtml;
  try {
    listHtml = renderList(template, categories, games);
  } catch (err) {
    console.error('[build] ' + err.message);
    process.exitCode = 1;
    return;
  }

  var catMap = data.categoryMap(categories);
  var detailHtml = Object.create(null);
  games.forEach(function (game) {
    detailHtml[game.slug] = renderDetail(game, catMap);
  });

  var slugs = games.map(function (game) { return game.slug; });
  var stale = staleGeneratedDirs(opts.out, slugs);

  if (opts.check) {
    var problems = [];
    var listPath = path.join(opts.out, 'index.html');
    if (!fs.existsSync(listPath)) problems.push('missing ' + listPath);
    else if (fs.readFileSync(listPath, 'utf8') !== listHtml) problems.push('list page is stale: ' + listPath);
    games.forEach(function (game) {
      var file = path.join(opts.out, game.slug, 'index.html');
      if (!fs.existsSync(file)) problems.push('missing detail page: ' + file);
      else if (fs.readFileSync(file, 'utf8') !== detailHtml[game.slug]) problems.push('stale detail page: ' + file);
    });
    stale.forEach(function (name) { problems.push('stale generated directory: ' + path.join(opts.out, name)); });
    if (problems.length) {
      console.error('[check] FAIL (' + problems.length + ' problem' + (problems.length === 1 ? '' : 's') + ')');
      problems.slice(0, 40).forEach(function (p) { console.error('  ' + p); });
      process.exitCode = 1;
      return;
    }
    console.log('[check] OK: ' + games.length + ' games, ' + games.length + ' detail pages, list page up to date');
    return;
  }

  var changed = 0;
  if (writeIfChanged(path.join(opts.out, 'index.html'), listHtml)) changed++;
  games.forEach(function (game) {
    if (writeIfChanged(path.join(opts.out, game.slug, 'index.html'), detailHtml[game.slug])) changed++;
  });
  stale.forEach(function (name) {
    fs.rmSync(path.join(opts.out, name), { recursive: true, force: true });
    changed++;
  });

  if (!opts.quiet) {
    console.log('[build] ' + games.length + ' games · ' + categories.length + ' categories · ' +
      games.length + ' detail pages · ' + changed + ' file' + (changed === 1 ? '' : 's') + ' changed');
    var relOut = path.relative(process.cwd(), opts.out) || '.';
    console.log('[build] output: ' + relOut + '/');
  }
}

