/* Games hall — offline service worker.
   Scope: /games/ only. No analytics, no reporting, no cross-origin fetches.

   Manifest groups (generated by scripts/gen-precache.js):
     shell   — precached during install: hall, offline page, web app manifest,
               hall/offline icons, and the shared runtime the hall loads. The generator enforces
               a 2 MB install budget.
     lazy    — game pages + page scripts/styles + registry/data. NOT precached.
     runtime — images/fonts. NOT precached.

   Fetch strategy, stated explicitly:
   - Navigations (`request.mode === 'navigate'`): network-first with cache
     fallback, then /games/offline.html. A page visited once while this worker
     controls it is offline-capable afterwards.
   - Other same-origin /games/ GETs: stale-while-revalidate. This is how lazy
     page assets and runtime images/fonts become available offline after the
     first successful load: install does not need to fetch them up front.
   - Caveat: the very first navigation that registers this worker is not yet
     controlled, so neither it nor its subresources are cached by the SW on
     that initial load. They are cached on the next controlled visit/reload.

   The precache list is NOT maintained here. It lives in
   games/precache-manifest.js, generated by scripts/gen-precache.js from a
   real directory scan plus games/registry.json. */
'use strict';

// Bump on every precache/logic change. The generator reads this constant, so
// the two changes ship together:
//   1. change CACHE_VERSION here, then
//   2. run `node scripts/gen-precache.js`
// v21 introduced the shell/lazy/runtime split. After changing the group schema
// (or any PRECACHE_* logic) you MUST re-run the generator: this worker refuses
// to install a manifest whose version does not match.
var CACHE_VERSION = 'v24';
var CACHE_PREFIX = 'hhfa-games-';
var CACHE_NAME = CACHE_PREFIX + CACHE_VERSION;

// importScripts is synchronous in a worker. Read it defensively; a missing
// or empty manifest makes install fail below rather than activating a
// cache-less worker and deleting a working offline cache.
var PRECACHE_MANIFEST = null;
try {
  importScripts('/games/precache-manifest.js');
  PRECACHE_MANIFEST = self.GAMES_PRECACHE_MANIFEST || null;
} catch (err) {
  if (typeof console !== 'undefined') {
    console.warn('[games-sw] precache manifest unavailable:', err);
  }
}

if (PRECACHE_MANIFEST && PRECACHE_MANIFEST.version !== CACHE_VERSION) {
  if (typeof console !== 'undefined') {
    console.warn(
      '[games-sw] precache manifest is ' + PRECACHE_MANIFEST.version +
      ', expected ' + CACHE_VERSION +
      '; run `node scripts/gen-precache.js`'
    );
  }
}

// Only the shell group is fetched during install. lazy/runtime entries become
// part of the same cache on demand through the fetch handler below.
var PRECACHE_URLS = (PRECACHE_MANIFEST && PRECACHE_MANIFEST.groups &&
  Array.isArray(PRECACHE_MANIFEST.groups.shell))
  ? PRECACHE_MANIFEST.groups.shell
  : [];
var MANIFEST_READY = !!(
  PRECACHE_MANIFEST &&
  PRECACHE_MANIFEST.version === CACHE_VERSION &&
  PRECACHE_URLS.length
);
var OFFLINE_URL = (PRECACHE_MANIFEST && PRECACHE_MANIFEST.offlineUrl) || '/games/offline.html';

// `cache: 'reload'` bypasses the HTTP cache so a new version never installs
// mixed old/new files from a stale intermediary cache. offline.html is
// excluded here and fetched by precacheOfflinePage(), which also repairs the
// redirect status; that keeps install requests exactly equal to the shell
// group (one request per shell URL, no duplicates).
var PRECACHE_REQUESTS = PRECACHE_URLS.filter(function (url) {
  return url !== OFFLINE_URL;
}).map(function (url) {
  return new Request(url, { cache: 'reload' });
});

self.addEventListener('install', function (event) {
  // Refuse to install a cache-less or stale-version worker over a good offline
  // cache. A mismatch means sw.js was bumped without re-running
  // scripts/gen-precache.js (or a proxy served the old manifest); the previous
  // worker keeps serving and the browser retries on the next update.
  if (!MANIFEST_READY) {
    event.waitUntil(Promise.reject(new Error(
      '[games-sw] precache manifest missing or not ' + CACHE_VERSION +
      '; run `node scripts/gen-precache.js`'
    )));
    return;
  }

  event.waitUntil(
    caches.open(CACHE_NAME).then(function (cache) {
      // cache.addAll() is all-or-nothing, so fall back to per-entry adds:
      // one missing optional file must not abort the whole installation.
      function addEach() {
        return Promise.all(PRECACHE_REQUESTS.map(function (request) {
          return cache.add(request).catch(function () {
            return null;
          });
        }));
      }

      var precache = PRECACHE_REQUESTS.length
        ? cache.addAll(PRECACHE_REQUESTS).catch(addEach)
        : Promise.resolve();

      return Promise.all([
        precache,
        precacheOfflinePage(cache).catch(function () { return null; })
      ]);
    })
    // Deliberately NO self.skipWaiting() here. The new worker stays in
    // `waiting`, so a game in progress keeps the exact cache it started with.
    //
    // Pages that show an "update ready" prompt can opt in early:
    //   reg.waiting.postMessage({ type: 'SKIP_WAITING' })
    // None of the current pages do. For them the waiting worker activates
    // naturally on the next cold start, when the last client controlled by
    // the old worker has gone away. It is not stranded: the browser releases
    // `waiting` as soon as no old-version client remains.
  );
});

// Opt-in early activation. Only a page in /games/ scope can send this.
self.addEventListener('message', function (event) {
  var data = event.data;
  if (data && typeof data === 'object' && data.type === 'SKIP_WAITING') {
    self.skipWaiting();
  }
});

self.addEventListener('activate', function (event) {
  event.waitUntil(
    caches.keys().then(function (keys) {
      return Promise.all(keys.filter(function (key) {
        return key.indexOf(CACHE_PREFIX) === 0 && key !== CACHE_NAME;
      }).map(function (key) {
        return caches.delete(key);
      }));
    }).then(function () {
      // Claim only after activation: open clients that navigated after this
      // point are controlled immediately, without interrupting the update.
      return self.clients.claim();
    })
  );
});

// Cloudflare Pages serves /games/offline.html as a 308 to /games/offline.
// A response fetched through that redirect keeps `redirected = true`, and the
// browser rejects such a response as a navigation reply (ERR_FAILED). Rebuild
// the body as a plain same-origin 200 so it is always safe to hand back.
function asPlain200(response) {
  if (!response) return response;
  return new Response(response.body, {
    status: 200,
    statusText: 'OK',
    headers: response.headers
  });
}

function precacheOfflinePage(cache) {
  var request = new Request(OFFLINE_URL, { redirect: 'follow', cache: 'reload' });
  return fetch(request).then(function (response) {
    if (!response.ok) {
      throw new Error('offline page responded with ' + response.status);
    }
    return cache.put(OFFLINE_URL, asPlain200(response));
  });
}

function pageFallback(request) {
  var url = new URL(request.url);
  var key = url.origin + url.pathname;
  return caches.open(CACHE_NAME).then(function (cache) {
    return cache.match(key).then(function (hit) {
      if (hit) return hit;
      if (url.pathname.slice(-1) === '/') {
        return cache.match(key + 'index.html');
      }
      if (url.pathname.slice(-11) === '/index.html') {
        return cache.match(key.slice(0, -10));
      }
      return null;
    });
  });
}

// NAVIGATION POLICY: network-first.
// The fresh page wins when online; the response is copied into the cache so a
// page the user has actually opened survives going offline. The cache write is
// awaited before the response is handed back: once a controlled navigation
// finishes, the page really is in the cache (a fire-and-forget put could be
// lost if the worker is killed). If the network fails we serve the cached page
// (both /dir/ and /dir/index.html keys), then /games/offline.html. This is what
// keeps the *current* page offline; game pages in the lazy group are cached
// here on first controlled visit rather than at install.
function networkFirst(request) {
  return fetch(request).then(function (response) {
    if (!response || !response.ok) return response;
    var copy = response.clone();
    return caches.open(CACHE_NAME).then(function (cache) {
      return cache.put(request, copy);
    }).catch(function () {}).then(function () {
      return response;
    });
  }).catch(function () {
    return pageFallback(request).then(function (hit) {
      if (hit) return asPlain200(hit);
      return caches.match(OFFLINE_URL).then(function (offline) {
        if (offline) return asPlain200(offline);
        return new Response('当前离线，且这个页面尚未缓存。', {
          status: 503,
          headers: { 'Content-Type': 'text/plain; charset=utf-8' }
        });
      });
    });
  });
}

// ASSET POLICY: stale-while-revalidate.
// Covers lazy page scripts/styles and runtime images/fonts: a cached copy is
// returned immediately while a background fetch refreshes it. On a first miss
// the network response is awaited into the cache before being returned, so a
// page's direct dependencies are offline-capable after one controlled load,
// without putting them in the install budget.
function staleWhileRevalidate(request) {
  return caches.open(CACHE_NAME).then(function (cache) {
    return cache.match(request).then(function (hit) {
      if (hit) {
        // Cached copy wins; refresh in the background without delaying it.
        fetch(request).then(function (response) {
          if (response && response.ok && response.type === 'basic') {
            cache.put(request, response.clone()).catch(function () {});
          }
        }).catch(function () {});
        return hit;
      }

      return fetch(request).then(function (response) {
        if (response && response.ok && response.type === 'basic') {
          var copy = response.clone();
          return cache.put(request, copy).catch(function () {}).then(function () {
            return response;
          });
        }
        return response;
      }).catch(function () {
        return new Response('', { status: 504, statusText: 'Offline' });
      });
    });
  });
}

self.addEventListener('fetch', function (event) {
  var request = event.request;
  if (request.method !== 'GET') return;

  var url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.indexOf('/games/') !== 0) return;

  if (request.mode === 'navigate') {
    event.respondWith(networkFirst(request));
    return;
  }

  event.respondWith(staleWhileRevalidate(request));
});
