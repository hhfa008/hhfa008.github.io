/** Convert a px size measured against a 120px-wide face into container units. */
function cq(px) {
  return `${((px / 120) * 100).toFixed(2)}cqw`;
}

function escapeHTML(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
}

function pipSizeFor(rank) {
  if (rank === '2' || rank === '3') return 34;
  if (rank === '4' || rank === '5' || rank === '6') return 28;
  return 24;
}

/** 54 poker cards: 52 standard cards followed by the two jokers. */
export function pokerCards() {
  const cards = [];
  for (const suit of POKER_SUITS) {
    for (const rank of POKER_RANKS) {
      const isTen = rank === '10';
      const isAce = rank === 'A';
      const isCourt = rank === 'J' || rank === 'Q' || rank === 'K';
      const cornerFontSize = isTen ? 19 : 24;
      const faceFontSize = isAce ? 64 : isCourt ? 58 : pipSizeFor(rank);
      cards.push({
        kind: 'poker',
        id: `${rank}${suit.letter}`,
        rank,
        suit: suit.key,
        suitSymbol: suit.symbol,
        color: suit.color,
        label: `${rank}${suit.symbol}`,
        glyph: suit.symbol,
        fontFamily: FONT_STACK,
        fontSize: cornerFontSize,
        cornerFontSize,
        faceFontSize,
        pips: isAce || isCourt ? [] : POKER_PIPS[rank].map(([x, y]) => ({ x, y })),
        joker: false,
        exportPath: `poker/${rank}${suit.letter}.png`,
      });
    }
  }

  cards.push({
    kind: 'poker',
    id: 'joker-small',
    rank: 'JOKER',
    suit: 'joker',
    suitSymbol: '王',
    color: 'black',
    label: '小王',
    glyph: '王',
    fontFamily: FONT_STACK,
    fontSize: 22,
    cornerFontSize: 10,
    faceFontSize: 46,
    pips: [],
    joker: 'small',
    jokerName: '小王',
    exportPath: 'poker/joker-small.png',
  });

  cards.push({
    kind: 'poker',
    id: 'joker-big',
    rank: 'JOKER',
    suit: 'joker',
    suitSymbol: '王',
    color: 'red',
    label: '大王',
    glyph: '王',
    fontFamily: FONT_STACK,
    fontSize: 22,
    cornerFontSize: 10,
    faceFontSize: 52,
    pips: [],
    joker: 'big',
    jokerName: '大王',
    exportPath: 'poker/joker-big.png',
  });

  return cards;
}

/** 34 mahjong tiles: wan/tong/tiao 1-9 plus winds and dragons. */
export function mahjongTiles() {
  const tiles = [];

  for (let value = 1; value <= 9; value += 1) {
    tiles.push({
      kind: 'mahjong',
      id: `wan-${value}`,
      suit: 'wan',
      value,
      glyph: HAN_NUMERALS[value],
      unit: '萬',
      label: `${HAN_NUMERALS[value]}萬`,
      fontSize: 44,
      numFontSize: 40,
      unitFontSize: 38,
      exportPath: `mahjong/wan-${value}.png`,
    });
  }

  for (let value = 1; value <= 9; value += 1) {
    tiles.push({
      kind: 'mahjong',
      id: `tong-${value}`,
      suit: 'tong',
      value,
      glyph: '筒',
      label: `${value}筒`,
      fontSize: 34,
      dots: MJ_DOTS[value].map(([x, y, w]) => ({ x, y, w })),
      exportPath: `mahjong/tong-${value}.png`,
    });
  }

  for (let value = 1; value <= 9; value += 1) {
    tiles.push({
      kind: 'mahjong',
      id: `tiao-${value}`,
      suit: 'tiao',
      value,
      glyph: value === 1 ? '鸟' : '条',
      label: `${value}条`,
      fontSize: 34,
      bird: value === 1,
      sticks: value === 1 ? [] : MJ_STICKS[value].map(([x, y, h]) => ({ x, y, h })),
      exportPath: `mahjong/tiao-${value}.png`,
    });
  }

  for (const wind of WINDS) {
    tiles.push({
      kind: 'mahjong',
      id: wind.id,
      suit: 'wind',
      value: Number(wind.id.slice(-1)),
      glyph: wind.glyph,
      label: wind.label,
      fontSize: 58,
      tone: 'wind',
      exportPath: `mahjong/${wind.id}.png`,
    });
  }

  for (const dragon of DRAGONS) {
    tiles.push({
      kind: 'mahjong',
      id: dragon.id,
      suit: 'dragon',
      value: Number(dragon.id.slice(-1)),
      glyph: dragon.glyph,
      label: dragon.label,
      fontSize: 58,
      tone: dragon.tone,
      exportPath: `mahjong/${dragon.id}.png`,
    });
  }

  return tiles;
}

/** 14 xiangqi pieces, traditional forms: red 帥仕相馬車炮兵 / black 將士象馬車砲卒. */
export function chessPieces() {
  return CHESS_PIECES.map(({ side, slug, glyph, label }) => ({
    kind: 'chess',
    id: `${side}-${slug}`,
    side,
    slug,
    glyph,
    label,
    fontFamily: '"STKaiti", "Songti SC", "PingFang SC", serif',
    fontSize: 52,
    exportPath: `chess/${side}-${slug}.png`,
  }));
}

export function allCards() {
  return [...pokerCards(), ...mahjongTiles(), ...chessPieces()];
}

function pokerCorner(item, position) {
  const rankSize = cq(item.cornerFontSize);
  const suitSize = cq(item.cornerFontSize * 0.76);
  return `<span class="ca-corner ca-corner-${position}">
      <b style="font-size:${rankSize}">${escapeHTML(item.rank)}</b>
      <i style="font-size:${suitSize}">${escapeHTML(item.suitSymbol)}</i>
    </span>`;
}

function pokerHTML(item) {
  const tone = item.color === 'red' ? 'ca-red' : 'ca-black';
  const corners = `${pokerCorner(item, 'tl')}${pokerCorner(item, 'br')}`;

  if (item.joker) {
    return `<article class="ca-face ca-poker ${tone} ca-joker-card" data-card-id="${escapeHTML(item.id)}" aria-label="${escapeHTML(item.label)}">
      <span class="ca-corner ca-corner-tl ca-joker-corner"><b style="font-size:${cq(9)}">JOKER</b><i style="font-size:${cq(13)}">王</i></span>
      <span class="ca-corner ca-corner-br ca-joker-corner"><b style="font-size:${cq(9)}">JOKER</b><i style="font-size:${cq(13)}">王</i></span>
      <div class="ca-joker-face">
        <span class="ca-joker-tag" style="font-size:${cq(10)}">JOKER</span>
        <span class="ca-joker-word" style="font-size:${cq(item.faceFontSize)}">${escapeHTML(item.jokerName)}</span>
        <span class="ca-joker-suit" style="font-size:${cq(24)}">王</span>
      </div>
    </article>`;
  }

  let center = '';
  if (item.rank === 'A') {
    center = `<div class="ca-center ca-ace"><span class="ca-ace-suit" style="font-size:${cq(item.faceFontSize)}">${escapeHTML(item.suitSymbol)}</span></div>`;
  } else if (item.rank === 'J' || item.rank === 'Q' || item.rank === 'K') {
    center = `<div class="ca-center ca-court">
        <span class="ca-court-rule"></span>
        <span class="ca-court-letter" style="font-size:${cq(item.faceFontSize)}">${escapeHTML(item.rank)}</span>
        <span class="ca-court-suit" style="font-size:${cq(item.faceFontSize * 0.5)}">${escapeHTML(item.suitSymbol)}</span>
        <span class="ca-court-rule"></span>
      </div>`;
  } else {
    const pips = item.pips
      .map(
        (pip) =>
          `<span class="ca-pip" style="left:${pip.x}%;top:${pip.y}%;font-size:${cq(item.faceFontSize)}">${escapeHTML(
            item.suitSymbol,
          )}</span>`,
      )
      .join('');
    center = `<div class="ca-center ca-pips">${pips}</div>`;
  }

  return `<article class="ca-face ca-poker ${tone}" data-card-id="${escapeHTML(item.id)}" aria-label="${escapeHTML(item.label)}">
    ${corners}${center}
  </article>`;
}

function mahjongHTML(item) {
  let face = '';
  if (item.suit === 'wan') {
    face = `<span class="ca-mj-num" style="font-size:${cq(item.numFontSize)}">${escapeHTML(item.glyph)}</span>
      <span class="ca-mj-unit" style="font-size:${cq(item.unitFontSize)}">${escapeHTML(item.unit)}</span>`;
  } else if (item.suit === 'tong') {
    face = item.dots
      .map(
        (dot) =>
          `<span class="ca-dot" style="left:${dot.x}%;top:${dot.y}%;width:${cq(dot.w)}"></span>`,
      )
      .join('');
  } else if (item.suit === 'tiao') {
    if (item.bird) {
      face = `<span class="ca-bird">
        <svg viewBox="0 0 100 120" role="img" aria-label="一条">
          <path d="M52 16c13 0 22 9 22 21 0 5-2 9-5 12 11 5 19 15 23 28-12 2-23-1-31-7-4 11-12 18-25 21 2-10 6-18 13-23-9-2-16-8-20-15 9-2 17-1 23 3-2-9 1-17 7-22-2-2-4-5-4-9 0-6 6-9 13-9z" fill="#2f7d4a"/>
          <path d="M39 29l-9-8 12 3z" fill="#b8433b"/>
          <circle cx="42" cy="31" r="2.6" fill="#123322"/>
          <path d="M28 69l-17 8 17 5z" fill="#b8433b"/>
          <path d="M57 95l-4 13M66 93l3 14" stroke="#8a6234" stroke-width="3" fill="none" stroke-linecap="round"/>
        </svg>
      </span>`;
    } else {
      face = item.sticks
        .map(
          (stick) =>
            `<span class="ca-stick" style="left:${stick.x}%;top:${stick.y}%;height:${stick.h}%"></span>`,
        )
        .join('');
    }
  } else {
    face = `<span class="ca-mj-honor ca-tone-${item.tone}" style="font-size:${cq(item.fontSize)}">${escapeHTML(
      item.glyph,
    )}</span>`;
  }

  return `<article class="ca-face ca-mahjong ca-mj-${item.suit}" data-card-id="${escapeHTML(item.id)}" aria-label="${escapeHTML(
    item.label,
  )}">
    <span class="ca-mj-inner" style="font-size:${cq(item.fontSize)}">${face}</span>
  </article>`;
}

function chessHTML(item) {
  return `<article class="ca-face ca-chess ca-chess-${item.side}" data-card-id="${escapeHTML(item.id)}" aria-label="${escapeHTML(
    item.label,
  )}">
    <span class="ca-chess-rim"></span>
    <span class="ca-chess-glyph" style="font-size:${cq(item.fontSize)}">${escapeHTML(item.glyph)}</span>
  </article>`;
}

/**
 * Return the full face markup for one item.
 * @param {object} item
 * @returns {string}
 */
export function cardHTML(item) {
  if (!item || typeof item !== 'object') {
    throw new TypeError('cardHTML(item) requires a card item');
  }
  if (item.kind === 'poker') return pokerHTML(item);
  if (item.kind === 'mahjong') return mahjongHTML(item);
  if (item.kind === 'chess') return chessHTML(item);
  throw new TypeError(`Unknown card kind: ${String(item.kind)}`);
}

/**
 * Build a DOM element for one item.
 *
 * renderCard(item)               -> returns a new element
 * renderCard(targetElement, item)  -> appends one face and returns the element
 * renderCard(targetElement)        -> appends all 102 faces and returns the array
 *
 * @param {Element|object} targetOrItem
 * @param {object} [maybeItem]
 * @returns {HTMLElement|HTMLElement[]}
 */
export function renderCard(targetOrItem, maybeItem) {
  if (typeof document === 'undefined') {
    throw new Error('renderCard() needs a browser DOM; use cardHTML() in Node');
  }
  if (
    maybeItem === undefined &&
    targetOrItem &&
    typeof targetOrItem === 'object' &&
    typeof targetOrItem.appendChild === 'function'
  ) {
    return allCards().map((item) => renderCard(targetOrItem, item));
  }
  const hasTarget = maybeItem !== undefined;
  const item = hasTarget ? maybeItem : targetOrItem;
  const target = hasTarget ? targetOrItem : null;
  const template = document.createElement('template');
  template.innerHTML = cardHTML(item).trim();
  const el = template.content.firstElementChild;
  if (target && typeof target.appendChild === 'function') target.appendChild(el);
  return el;
}

