/**
 * cardart.js — 102 board-game card faces, drawn with DOM + system fonts only.
 *
 * No images, no external fonts, no third-party libraries, no canvas.
 * Every face is plain markup so it can be embedded in a 3D table scene and
 * screenshotted deterministically by Playwright.
 *
 * Counts:
 *   pokerCards()   -> 54  (52 + small/big joker)
 *   mahjongTiles() -> 34  (9 wan + 9 tong + 9 tiao + 4 winds + 3 dragons)
 *   chessPieces()  -> 14  (7 red + 7 black, traditional glyphs)
 *
 * Font stack is intentionally limited to system UI / PingFang SC / Songti SC /
 * STKaiti. Chinese glyphs are text, never generated by an image model.
 */

