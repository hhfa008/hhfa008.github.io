'use strict';

/*
 * Pure helpers shared by the boardgame build and its tests.
 * No browser APIs and no third-party dependencies.
 */

export const CATEGORY_ORDER = ['euro', 'party', 'ameritrash', 'card', 'two-player', 'family'];

export const CATEGORY_LABELS = {
  euro: '德式策略',
  party: '毛线派对',
  ameritrash: '美式',
  card: '卡牌',
  'two-player': '双人',
  family: '家庭'
};

export function escapeHtml(value) {
  return String(value == null ? '' : value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export function formatRange(min, max, unit) {
  const suffix = unit ? ' ' + unit : '';
  return min === max ? String(min) + suffix : min + '–' + max + suffix;
}

// Time filter buckets are keyed on the game's maximum play time, so a bucket
// is unambiguous for games whose range straddles a boundary.
export function timeBucket(maxMinutes) {
  if (maxMinutes <= 30) return '30';
  if (maxMinutes <= 60) return '60';
  if (maxMinutes <= 120) return '120';
  return '120plus';
}

// Mirrors the inline filter script generated by build.mjs. The browser copy is
// tiny on purpose; tests import this function to lock the semantics down.
export function filterGames(games, filters) {
  const f = filters || {};
  const q = String(f.q || '').trim().toLowerCase();
  return games.filter(function (game) {
    if (f.category && f.category !== 'all' && game.category !== f.category) return false;

    if (f.players != null && f.players !== 'all') {
      const n = Number(f.players);
      if (n >= 5) {
        if (game.players.max < 5) return false;
      } else if (!(game.players.min <= n && n <= game.players.max)) {
        return false;
      }
    }

    if (f.time && f.time !== 'all' && timeBucket(game.playTime.max) !== f.time) return false;

    if (q) {
      const haystack = [
        game.name.zh,
        game.name.en,
        game.slug,
        game.designers.join(' '),
        game.publishers.join(' ')
      ].join(' ').toLowerCase();
      if (haystack.indexOf(q) === -1) return false;
    }

    return true;
  });
}

export function recommend(games, game, count) {
  const n = count == null ? 3 : count;
  return games
    .filter(function (other) {
      return other.id !== game.id && other.category === game.category;
    })
    .sort(function (a, b) {
      if (b.rating !== a.rating) return b.rating - a.rating;
      return a.id.localeCompare(b.id);
    })
    .slice(0, n);
}

export function sortGames(games) {
  const order = new Map(CATEGORY_ORDER.map(function (key, i) { return [key, i]; }));
  return games.slice().sort(function (a, b) {
    const ca = order.has(a.category) ? order.get(a.category) : 99;
    const cb = order.has(b.category) ? order.get(b.category) : 99;
    if (ca !== cb) return ca - cb;
    if (b.rating !== a.rating) return b.rating - a.rating;
    return a.id.localeCompare(b.id);
  });
}

export function categoryCounts(games) {
  const counts = {};
  CATEGORY_ORDER.forEach(function (key) { counts[key] = 0; });
  games.forEach(function (game) {
    if (counts[game.category] == null) counts[game.category] = 0;
    counts[game.category] += 1;
  });
  return counts;
}
